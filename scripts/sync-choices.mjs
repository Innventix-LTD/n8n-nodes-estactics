// Writes the country / language options of Create a Lead from the Zapier app choices (copied from the backend), so every app offers the same values.
// The node can't read files at runtime (n8n verification rule), so the options are generated into a TypeScript file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const choicesPath = fileURLToPath(new URL('../../zapier/lib/choices.json', import.meta.url));
const outputPath = fileURLToPath(new URL('../nodes/Estactics/shared/choices.ts', import.meta.url));

export const renderChoices = ({ countries, countryLabels, languages }) => {
	const quote = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
	// INFO: Values are kept exactly as the backend list (some have a trailing space), labels are trimmed.
	const renderChoices = (constName, choices) =>
		[
			`const ${constName}: Record<string, string> = {`,
			...Object.entries(choices).map(([value, label]) => `\t${quote(value)}: ${quote(label.trim())},`),
			'};',
			'',
		].join('\n');

	// INFO: Built from value → label maps at runtime, so the country names are shown as is (the node lint would title-case "and", "of").
	return [
		"// Generated by `npm run sync-choices` from integrations/zapier/lib/choices.json, don't edit.",
		"import type { INodePropertyOptions } from 'n8n-workflow';",
		'',
		renderChoices('COUNTRY_CODES', countries),
		renderChoices('COUNTRY_LABELS', countryLabels),
		renderChoices('LANGUAGES', languages),
		'const toOptions = (choices: Record<string, string>): INodePropertyOptions[] =>',
		'\tObject.entries(choices).map(([value, name]) => ({ name, value }));',
		'',
		'export const countryCodeOptions = toOptions(COUNTRY_CODES);',
		'export const countryOptions = toOptions(COUNTRY_LABELS);',
		'export const languageOptions = toOptions(LANGUAGES);',
		'',
	].join('\n');
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(outputPath, renderChoices(JSON.parse(readFileSync(choicesPath, 'utf8'))));
	console.log('Create a Lead choices synced.');
}
